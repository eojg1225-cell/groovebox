// The engine for the web build: the native crate (native/, Rust) compiled to WebAssembly and
// written as base64 into src/worklet/engineWasm.gen.ts (not committed), which the worklet
// bundle carries, so the worklet stays one self-contained file (the Artifact's too).
// Usage: node scripts/build-wasm.mjs (npm run build:wasm; dev, build and test run it first).
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const TARGET = 'wasm32-unknown-unknown';
execFileSync('cargo', ['build', '--release', '--lib', '--target', TARGET], { cwd: 'native', stdio: 'inherit' });
const wasm = readFileSync(`native/target/${TARGET}/release/groovebox_native.wasm`);
const out = 'src/worklet/engineWasm.gen.ts';
const text = `// Generated by scripts/build-wasm.mjs from native/ (the Rust engine): do not edit.\nexport const ENGINE_WASM = '${wasm.toString('base64')}';\n`;
let old = '';
try { old = readFileSync(out, 'utf8'); } catch { /* first build */ }
if (old !== text) writeFileSync(out, text);
console.log(`${out}: ${(wasm.length / 1024).toFixed(0)} KB of WebAssembly`);
