/**
 * The native engine's parameter tables (native/src/specs.rs), generated from the TypeScript
 * ones: every type's parameters in slot order, the type gains, the mixer / bus / LFO / ARP
 * specs, the live macros and the PAD's linked knobs. Fails when the file no longer matches:
 * rewrite it with `UPDATE_VECTORS=1 npx vitest run tests/nativeSpecs.test.ts`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import type { ParamSpec } from '../src/engine/params';
import { MIX_PARAMS } from '../src/engine/mixParams';
import { ARP_PARAMS } from '../src/engine/arp';
import { LFO_PARAMS } from '../src/engine/lfo';
import { BUS_PARAMS } from '../src/fx/buses';
import { INSTRUMENTS, LIVE_MACROS, SOUND_KINDS, linkedParams } from '../src/instruments/registry';

const FILE = 'native/src/specs.rs';

const num = (v: number) => {
  const s = String(v);
  return /[.eE]/.test(s) ? s : `${s}.0`;
};
const curve = (c: ParamSpec['curve']) => ({ linear: 'Linear', exp: 'Exp', square: 'Square', power: 'Power' })[c];
const spec = (p: ParamSpec) =>
  `Spec { id: "${p.id}", min: ${num(p.min)}, max: ${num(p.max)}, default: ${num(p.defaultValue)}, curve: Curve::${curve(p.curve)}, power: ${num(p.power ?? 2)}, options: ${p.options?.length ?? 0}, coarse: ${p.coarse === true} }`;
const list = (name: string, specs: readonly ParamSpec[]) => `pub static ${name}: [Spec; ${specs.length}] = [\n${specs.map((p) => `    ${spec(p)},`).join('\n')}\n];\n`;
const upper = (k: string) => k.toUpperCase();

function generate(): string {
  let out = `//! Generated by tests/nativeSpecs.test.ts from the TypeScript tables: do not edit by hand.\n\nuse crate::kind::SoundKind;\nuse crate::params::{Curve, Spec};\n\n`;
  for (const k of SOUND_KINDS) out += list(`${upper(k)}_PARAMS`, INSTRUMENTS[k].params);
  out += `\n/// A type's parameters in slot order (the engine's LOCK slots).\npub fn kind_params(kind: SoundKind) -> &'static [Spec] {\n    match kind {\n${SOUND_KINDS.map((k) => `        SoundKind::${k[0].toUpperCase()}${k.slice(1)} => &${upper(k)}_PARAMS,`).join('\n')}\n    }\n}\n`;
  out += `\n/// The type's output trim (InstrumentEntry.gain).\npub fn type_gain(kind: SoundKind) -> f64 {\n    match kind {\n${SOUND_KINDS.map((k) => `        SoundKind::${k[0].toUpperCase()}${k.slice(1)} => ${num(INSTRUMENTS[k].gain ?? 1)},`).join('\n')}\n    }\n}\n\n`;
  out += list('MIX_PARAMS', MIX_PARAMS);
  BUS_PARAMS.forEach((b, i) => { out += list(`BUS${i}_PARAMS`, b); });
  out += list('LFO_PARAMS', Object.values(LFO_PARAMS));
  out += list('ARP_PARAMS', ARP_PARAMS);
  out += `\n/// A live macro's targets: (param id, amount, top).\npub type Macro = (&'static str, &'static [(&'static str, f64, bool)]);\n\n/// LIVE_MACROS per type.\npub fn live_macros(kind: SoundKind) -> &'static [Macro] {\n    match kind {\n`;
  for (const k of SOUND_KINDS) {
    const ms = LIVE_MACROS[k].map((m) => `("${m.id}", &[${m.targets.map((t) => `("${t.id}", ${num(t.amount)}, ${t.top === true})`).join(', ')}])`);
    out += `        SoundKind::${k[0].toUpperCase()}${k.slice(1)} => &[${ms.join(', ')}],\n`;
  }
  out += `    }\n}\n`;
  out += `\n/// Parameters a SOUND page knob on \`id\` sets along with it (registry linkedParams).\npub fn linked_params(kind: SoundKind, id: &str) -> &'static [&'static str] {\n    match (kind, id) {\n`;
  for (const k of SOUND_KINDS) for (const p of INSTRUMENTS[k].params) {
    const l = linkedParams(k, p.id);
    if (l.length) out += `        (SoundKind::${k[0].toUpperCase()}${k.slice(1)}, "${p.id}") => &[${l.map((x) => `"${x}"`).join(', ')}],\n`;
  }
  out += `        _ => &[],\n    }\n}\n`;
  return out;
}

describe('native engine specs', () => {
  it(`${FILE} matches the TypeScript tables`, () => {
    const text = generate();
    if (process.env.UPDATE_VECTORS) writeFileSync(FILE, text);
    expect(readFileSync(FILE, 'utf8')).toBe(text);
  });
});
